const applyLanguage = language => {
  currentLanguage = language;
  root.lang = language;
  root.dir = language === "fa" ? "rtl" : "ltr";
  document.title = language === "fa" ? `${profile.fa.name} — طراح و توسعه‌دهنده وردپرس` : `${profile.en.name} — WordPress Developer`;
  if (metaDescription) metaDescription.setAttribute("content", translations[language].metaDescription);

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (translations[language][key] !== undefined) element.textContent = translations[language][key];
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
    const key = element.dataset.i18nAriaLabel;
    if (translations[language][key] !== undefined) element.setAttribute("aria-label", translations[language][key]);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach(element => {
    const key = element.dataset.i18nAlt;
    if (translations[language][key] !== undefined) element.setAttribute("alt", translations[language][key]);
  });

  document.querySelectorAll("[data-lang-label]").forEach(item => item.classList.toggle("active", item.dataset.langLabel === language));
  localStorage.setItem("saman-portfolio-language", language);
};

const setupPreloader = () => {
  let value = 0;
  let done = false;
  const tick = () => {
    if (done) return;
    value = Math.min(94, value + Math.ceil(Math.random() * 12));
    if (loaderPercent) loaderPercent.textContent = `${String(value).padStart(2, "0")}%`;
    if (value < 94) setTimeout(tick, 42);
  };
  tick();

  const finish = () => {
    if (done) return;
    done = true;
    if (loaderPercent) loaderPercent.textContent = "100%";
    setTimeout(() => preloader?.classList.add("is-hidden"), 120);
  };

  if (document.readyState === "complete") finish();
  else addEventListener("load", finish, { once: true });
  setTimeout(finish, 1300);
};

const openCommand = () => {
  commandPalette.classList.add("open");
  commandPalette.setAttribute("aria-hidden", "false");
  body.style.overflow = "hidden";
};

const closeCommand = () => {
  commandPalette.classList.remove("open");
  commandPalette.setAttribute("aria-hidden", "true");
  body.style.overflow = "";
};

const animateCursor = () => {
  ringX += (targetX - ringX) * .2;
  ringY += (targetY - ringY) * .2;
  cursorRing.style.left = `${ringX}px`;
  cursorRing.style.top = `${ringY}px`;
  cursorDot.style.left = `${targetX}px`;
  cursorDot.style.top = `${targetY}px`;
  cursorLabel.style.left = `${ringX}px`;
  cursorLabel.style.top = `${ringY - 40}px`;
  requestAnimationFrame(animateCursor);
};

const syncScroll = () => {
  const y = scrollY;
  const max = Math.max(1, document.documentElement.scrollHeight - innerHeight);
  scrollProgress.style.width = `${Math.min(100, Math.max(0, y / max * 100))}%`;
  siteHeader.classList.toggle("scrolled", y > 18);

  const heroHeight = Math.max(1, document.getElementById("hero").offsetHeight);
  const heroProgress = Math.min(1, y / heroHeight);
  if (gemStage) {
    gemStage.style.transform = `translateY(${-heroProgress * 18}px) scale(${1 - heroProgress * .045})`;
    gemStage.style.opacity = `${1 - heroProgress * .22}`;
  }
  if (heroCopy) heroCopy.style.opacity = `${1 - heroProgress * .28}`;

  const sections = [
    document.getElementById("hero"),
    document.getElementById("about"),
    document.getElementById("services"),
    document.getElementById("work"),
    document.getElementById("contact")
  ].filter(Boolean);
  const firstContentSection = document.getElementById("about");
  let current = y < Math.max(220, (firstContentSection?.offsetTop || innerHeight) - innerHeight * .5) ? "top" : "";
  const probe = y + 170;
  sections.forEach(section => {
    if (section.id === "hero") return;
    if (probe >= section.offsetTop && probe < section.offsetTop + section.offsetHeight) current = section.id;
  });
  document.querySelectorAll(".desktop-nav a, .mobile-menu a, .command-panel a").forEach(link => {
    link.classList.toggle("active", link.getAttribute("href") === `#${current}`);
  });
};

const setRevealOrder = () => {
  document.querySelectorAll(".deck-panel").forEach(panel => {
    const heading = panel.querySelector(".section-heading.reveal");
    if (heading) heading.style.setProperty("--reveal-delay", "0ms");

    panel.querySelectorAll(".project-card.reveal").forEach((item, index) => {
      item.style.setProperty("--reveal-delay", `${90 + index * 95}ms`);
    });

    panel.querySelectorAll(".service-card.reveal").forEach((item, index) => {
      item.style.setProperty("--reveal-delay", `${75 + index * 55}ms`);
    });

    const pluginCopy = panel.querySelector(".plugin-copy.reveal");
    const codeWindow = panel.querySelector(".code-window.reveal");
    if (pluginCopy) pluginCopy.style.setProperty("--reveal-delay", "0ms");
    if (codeWindow) codeWindow.style.setProperty("--reveal-delay", "130ms");

    const stackCloud = panel.querySelector(".stack-cloud.reveal");
    if (stackCloud) stackCloud.style.setProperty("--reveal-delay", "110ms");

    const contactCard = panel.querySelector(".contact-card.reveal");
    if (contactCard) contactCard.style.setProperty("--reveal-delay", "0ms");
  });
};

const setupReveal = () => {
  setRevealOrder();
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    });
  }, { threshold: .1, rootMargin: "0px 0px -6% 0px" });
  document.querySelectorAll(".reveal").forEach(node => observer.observe(node));
};

const setupMagnetic = () => {
  if (!finePointer) return;
  document.querySelectorAll(".magnetic").forEach(element => {
    element.addEventListener("pointermove", event => {
      const rect = element.getBoundingClientRect();
      const x = event.clientX - rect.left - rect.width / 2;
      const y = event.clientY - rect.top - rect.height / 2;
      element.style.transform = `translate(${x * .05}px, ${y * .05}px)`;
    });
    element.addEventListener("pointerleave", () => element.style.transform = "");
  });
};

const setupCursorStates = () => {
  if (!finePointer) return;
  document.querySelectorAll("a, button").forEach(element => {
    element.addEventListener("mouseenter", () => body.classList.add("cursor-hover"));
    element.addEventListener("mouseleave", () => body.classList.remove("cursor-hover"));
  });
  document.querySelectorAll(".project-link-hover").forEach(element => {
    element.addEventListener("mouseenter", () => body.classList.add("cursor-view"));
    element.addEventListener("mouseleave", () => body.classList.remove("cursor-view"));
  });
};

const applyPrismMode = active => {
  prismMode = active;
  body.classList.toggle("prism-mode", active);
  prismToggle.classList.toggle("active", active);
  localStorage.setItem("saman-prism-mode", active ? "on" : "off");
  if (window.setGemIntensity) window.setGemIntensity(active);
};

const init = () => {
  applyLanguage(currentLanguage);
  applyPrismMode(prismMode);
  setupPreloader();
  setupReveal();
  setupMagnetic();
  setupCursorStates();
  if (emailLink) emailLink.href = `mailto:${profile.email}`;
  const year = document.getElementById("year");
  if (year) year.textContent = new Date().getFullYear();
  syncScroll();
  if (finePointer) requestAnimationFrame(animateCursor);
};

languageSwitch.addEventListener("click", () => applyLanguage(currentLanguage === "en" ? "fa" : "en"));
menuToggle.addEventListener("click", () => {
  menuToggle.classList.toggle("active");
  mobileMenu.classList.toggle("active");
});
mobileMenu.querySelectorAll("a").forEach(link => link.addEventListener("click", () => {
  menuToggle.classList.remove("active");
  mobileMenu.classList.remove("active");
}));
commandToggle.addEventListener("click", openCommand);
commandBackdrop.addEventListener("click", closeCommand);
commandPalette.querySelectorAll("a").forEach(link => link.addEventListener("click", closeCommand));
prismToggle.addEventListener("click", () => applyPrismMode(!prismMode));
document.addEventListener("keydown", event => {
  if ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === "k") {
    event.preventDefault();
    commandPalette.classList.contains("open") ? closeCommand() : openCommand();
  }
  if (event.key === "Escape") closeCommand();
});
window.addEventListener("pointermove", event => {
  targetX = event.clientX;
  targetY = event.clientY;
  if (finePointer) {
    const target = event.target instanceof Element ? event.target : null;
    const onLightSurface = Boolean(target?.closest(".deck-panel"));
    body.classList.toggle("cursor-light", onLightSurface);
  }
}, { passive: true });
window.addEventListener("scroll", syncScroll, { passive: true });
window.addEventListener("resize", syncScroll);

init();
